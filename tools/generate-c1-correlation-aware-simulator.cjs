// Generate an isolated research simulator from the frozen C1 oracle. The only
// seam permits a caller to reorder the already eligible entry queue. Ranking,
// exits, sizing, costs, sector caps, stops and accounting remain canonical.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {createHash} = require('node:crypto');

const canonical = 'lib/c1AccountSimulator.js';
const target = 'lib/c1CorrelationAwareSimulator.js';
let source = fs.readFileSync(canonical, 'utf8');

assert.equal(
  createHash('sha256').update(source).digest('hex'),
  '63b1909359361e35ae7d0c2e833fecbb043013f7b337f9f2c96dc0a3adb2f31e',
  'Re-review the correlation-aware seam after any canonical simulator change',
);

function replace(from, to) {
  assert.equal(source.split(from).length, 2, 'Expected exactly one correlation-aware seam: ' + from.slice(0, 100));
  source = source.replace(from, to);
}

source = `// Generated by tools/generate-c1-correlation-aware-simulator.cjs.\n` +
  `// Offline research only. Do not edit or import from a production path.\n` + source;

replace(
  '      const rankedEligibleSignals = rankedSelection',
  '      let rankedEligibleSignals = rankedSelection',
);

replace(
`      const rankedTargetIndexBySymbol = new Map(
        rankedEligibleSignals.map((signal, index) => [symbolOf(signal), index]),
      );`,
`      if (
        rankedSelection &&
        rankRebalance &&
        typeof config.correlationAwareEntryOrder === "function"
      ) {
        const originalBySymbol = new Map(
          rankedEligibleSignals.map((signal) => [symbolOf(signal), signal]),
        );
        if (originalBySymbol.size !== rankedEligibleSignals.length)
          throw new Error("Correlation-aware entry queue requires unique symbols");
        const reordered = config.correlationAwareEntryOrder({
          signals: [...rankedEligibleSignals],
          heldSymbols: [...positions.keys()],
          sessionDate: session.date,
          rankedTargetCount,
          rankedEntryQueueCount: Math.max(
            rankedTargetCount,
            Math.floor(number(config.rankedEntryQueueCount, rankedTargetCount * 3)),
          ),
        });
        const orderedSymbols = Array.isArray(reordered)
          ? reordered.map(symbolOf)
          : [];
        if (
          orderedSymbols.length !== rankedEligibleSignals.length ||
          new Set(orderedSymbols).size !== orderedSymbols.length ||
          orderedSymbols.some((symbol) => !originalBySymbol.has(symbol))
        )
          throw new Error("Correlation-aware entry order changed the eligible set");
        rankedEligibleSignals = orderedSymbols.map((symbol) =>
          originalBySymbol.get(symbol),
        );
      }
      const rankedTargetIndexBySymbol = new Map(
        rankedEligibleSignals.map((signal, index) => [symbolOf(signal), index]),
      );`,
);

replace(
`          rank: researchRank(signal, config, rankContext),`,
`          rank:
            typeof config.correlationAwareEntryOrder === "function"
              ? rankedEligibleSignals.length - rankedTargetIndexBySymbol.get(symbol)
              : researchRank(signal, config, rankContext),`,
);

if (process.argv.includes('--check')) {
  assert.equal(
    fs.readFileSync(target, 'utf8'),
    source,
    'Regenerate the isolated correlation-aware simulator',
  );
} else {
  fs.writeFileSync(target, source);
}
