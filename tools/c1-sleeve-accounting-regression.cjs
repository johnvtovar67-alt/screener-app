const assert = require('node:assert/strict');
const { createResearchModuleLoader } = require('./research-module-loader.cjs');
const { createC1SleeveAccounting: create, applyC1SleeveFill: fill,
  restoreC1SleeveAccounting: restore, valueC1SleeveAccounting: value,
  proposeC1WholeShareReconciliation: reconcile } = createResearchModuleLoader(process.cwd()).load('lib/c1SleeveAccounting.js');
const initial = create(1000, '2026-09-01');
const buy = { id: 'b1', sleeve: 'base', date: '2026-09-02', symbol: 'TEST', side: 'buy', shares: 2, price: 100, fee: 1 };
const first = fill(initial, buy);
assert.equal(first.sleeves.base.cash, 49);
assert.equal(initial.sleeves.base.cash, 250, 'Updating one book must not mutate previous snapshots');
assert.equal(first.sleeves.cooldown15.cash, 500);
assert.equal(fill(first, buy), first, 'Network retry must not duplicate the trade');
assert.throws(() => fill(first, { ...buy, shares: 1 }), /Conflicting/);
assert.throws(() => fill(first, { ...buy, id: 'b2', shares: 1 }), /Insufficient/, 'Other sleeves cannot fund a purchase');
assert.throws(() => fill(first, { ...buy, id: 's2', side: 'sell', shares: 3 }), /oversell/);
assert.throws(() => fill(first, { ...buy, id: 'old', date: '2026-09-01', side: 'sell' }), /Out-of-order/);
assert.throws(() => fill(initial, { ...buy, date: '2026-02-31' }), /date/);
assert.throws(() => fill(initial, { ...buy, sleeve: '__proto__' }), /Unknown/);
assert.throws(() => value(first, {}), /Missing mark/);
const marked = value(first, { TEST: 110 });
assert.equal(marked.cash, 799); assert.equal(marked.equity, 1019);
const sold = fill(first, { ...buy, id: 's1', side: 'sell', price: 110 });
assert.equal(sold.sleeves.base.cash, 268);
assert.equal(value(sold, {}).equity, 1018, 'Both fill fees must be charged');
const corrupted = JSON.parse(JSON.stringify(first));
corrupted.sleeves.base.cash = 999999; corrupted.activationAuthorized = true;
const restored = restore(corrupted);
assert.equal(restored.sleeves.base.cash, 49, 'Restore must derive balances from fills');
assert.equal(restored.activationAuthorized, undefined, 'Model restore cannot import trading authority');
assert.throws(() => restore({ portfolio: [{ symbol: 'TEST', shares: 2 }] }), /history/);
assert.equal(JSON.stringify(restore(JSON.parse(JSON.stringify(first)))), JSON.stringify(first));
let fractional = fill(initial, { ...buy, shares: 0.75, fee: 0 });
fractional = fill(fractional, { ...buy, id: 'other', sleeve: 'sector40', shares: 0.75, fee: 0 });
const plan = reconcile({ state: fractional, prices: { TEST: 100, OLD: 50 }, heldShares: { OLD: 1 }, cash: 100 });
assert.equal(plan.orders.length, 2);
assert.equal(plan.orders[0].symbol, 'OLD'); assert.equal(plan.orders[0].side, 'sell');
assert.equal(plan.orders[1].shares, 1, 'Round only after combining sleeve interests');
assert.ok(Math.abs(plan.projectedCash - 49.82) < 1e-9, 'Slippage applies on both sides');
assert.equal(plan.executable, false);
assert.equal(reconcile({ state: fractional, prices: { TEST: 100 }, cash: 50 }).fundingPass, false);
assert.throws(() => reconcile({ state: fractional, prices: { TEST: 100 }, cash: 100, heldShares: { TEST: 0.5 } }), /Whole/);
console.log('PASS: independent sleeve cash, immutable fills, retry/restore integrity, fees, aggregate rounding and non-executable reconciliation.');
