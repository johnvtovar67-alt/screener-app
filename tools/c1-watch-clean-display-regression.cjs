const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const React=require('react'),{renderToStaticMarkup}=require('react-dom/server'),babel=require('next/dist/compiled/babel/core');
const {createResearchModuleLoader}=require('./research-module-loader.cjs');
const {createWorkflowFixture,currentEventEvidenceFor}=require('./fixtures/c1-trading-workflow.cjs');
const {applyAccountPolicyUniverseFixture}=require('./fixtures/c1-account-policy-universe.cjs');
const seam=require('./c1-watch-clean-display-seams.cjs'),fixture=require('./fixtures/c1-watch-clean-display-source-seams.json');
const file='components/C1AccountOpportunitiesView.js',source=fs.readFileSync(file,'utf8'),before=seam.restore(file,source);
assert.equal(seam.blob(source),fixture.files[file].afterHash);
assert.equal(seam.blob(before),fixture.files[file].beforeHash);
assert.equal(seam.restore(file,before),before);
assert.equal(seam.restore(file,source+'\n// unreviewed'),source+'\n// unreviewed');
assert.equal(seam.blob(before),require('./fixtures/c1-watch-numbering-source-seams.json').files[file].afterHash,'Prior numbering source identity remains unchanged');
const loader=createResearchModuleLoader(process.cwd());
const compiled=babel.transformSync(source,{filename:file,babelrc:false,configFile:false,presets:[[require.resolve('next/babel'),{'preset-env':{modules:'commonjs'}}]]}).code;
const record={exports:{}};
new Function('require','module','exports',compiled)(name=>name.startsWith('../lib/')?loader.load(name,path.resolve(file)):name==='react'?React:require(name.startsWith('@babel/runtime/')?'next/dist/compiled/'+name:name),record,record.exports);
(async()=>{
 const f=createWorkflowFixture('buy',{baselineDate:'2026-11-10',portfolio:[{symbol:'CASH',role:'Swing',shares:100000,avgCost:1}]});
 const spec=applyAccountPolicyUniverseFixture(f,{count:50});f.setCash(100000);
 const checked=await f.prepare();
 const events=new Map(currentEventEvidenceFor(spec.symbols,f.now).map(row=>[row.symbol,row]));
 const rows=f.screenRows().map(row=>({...row,eventRisk:events.get(row.symbol)}));
 const {joinC1Opportunities}=f.loader.load('lib/c1OpportunitiesContract.js');
 const input={...checked,screenRows:rows,positionRows:rows,screenCurrent:true,portfolio:f.portfolio};
 const joined=joinC1Opportunities(input,{readTime:()=>f.now}).projection;
 const original=JSON.stringify({input,account:f.account,watch:joined.watch,orders:joined.orders});
 const html=renderToStaticMarkup(record.exports.renderC1AccountOpportunitiesView(joined));
 const watch=html.slice(html.indexOf('aria-label="Watch opportunities"'));
 assert.match(watch,/1 is strongest/);
 assert.deepEqual([...watch.matchAll(/<tr[^>]*><td[^>]*>(\d+)<\/td>/g)].map(match=>Number(match[1])),Array.from({length:10},(_,i)=>i+1));
 assert(!/Download Watch details|universe|source candidates|monitoring candidates|Momentum rank/i.test(watch));
 assert(!watch.includes('MRNA'),'No MRNA explanation was added to the screener');
 assert(!/href=.*blob:/.test(watch));
 assert.equal(JSON.stringify({input,account:f.account,watch:joined.watch,orders:joined.orders}),original,'Rendering preserves candidates, orders and all financial facts');
 console.log('PASS: real account projection renders Watch 1–10 strongest first without download, universe figures or MRNA explanation; original selection, orders and financial facts remain identical.');
})().catch(error=>{console.error(error);process.exitCode=1;});
