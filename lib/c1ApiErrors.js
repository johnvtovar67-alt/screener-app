export function c1AccountApiFailure(error){
 if(isC1AccountSaveConflict(error))return {status:409,code:'ACCOUNT_SAVE_CONFLICT',retryable:false,
  error:'Another account update finished first. Reload the saved account and retry this change.'};
 const dependency=error&&typeof error==='object'?dependencyFailures.get(error):null;
 if(dependency)return {status:503,code:dependencies[dependency].code,retryable:true,error:dependencies[dependency].message};
 const message=String(error?.message||'');
 if(revisionConflicts.has(message))return {status:409,code:'ACCOUNT_REVISION_CONFLICT',retryable:false,error:message};
 if(validationMessages.has(message)||safeSymbolValidation.test(message))return {status:422,code:'ACCOUNT_VALIDATION_FAILED',retryable:false,error:message};
 if(unavailableMessages.has(message))return {status:503,code:'ACCOUNT_EVIDENCE_UNAVAILABLE',retryable:true,error:message};
 if(message==='An accepted account input changed; original account retained')return {status:500,code:'ACCOUNT_INPUT_INTEGRITY_FAILED',retryable:false,error:message};
 return {status:500,code:'ACCOUNT_ANALYSIS_FAILED',retryable:false,
  error:'Account verification failed; purchases remain paused. Reload the saved account before retrying changes.'};
}
