// Error presentation only. These tags never grant execution authority, retry a
// write, reinterpret an account record or weaken an existing domain guard.
const dependencyFailures=new WeakMap();
const dependencies=Object.freeze({
 storage:{code:'ACCOUNT_STORAGE_UNAVAILABLE',message:'Account storage is unavailable. Reload the saved account before retrying any changes.'},
 input:{code:'ACCOUNT_INPUT_UNAVAILABLE',message:'Current C1 session input is unavailable or unverified; purchases remain paused.'},
 portfolio:{code:'PORTFOLIO_VERIFICATION_UNAVAILABLE',message:'Saved portfolio verification is unavailable. Reload before retrying.'},
 holdings:{code:'HOLDING_VERIFICATION_UNAVAILABLE',message:'Holding-price verification is unavailable; purchases remain paused.'},
});

// Preserve the original ETag-conflict identity so the canonical bounded rebase
// in saveC1AccountUpdate remains unchanged. Hide arbitrary SDK/provider details.
export async function c1AccountDependency(task,kind){
 if(!Object.hasOwn(dependencies,kind))throw new Error('Unknown account dependency boundary');
 try{return await task();}
 catch(error){
  if(isC1AccountSaveConflict(error))throw error;
  const failure=new Error(dependencies[kind].message);
  dependencyFailures.set(failure,kind);
  throw failure;
 }
}

